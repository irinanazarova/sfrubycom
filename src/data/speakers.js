// Helper functions
export function getSpeaker(speakerId) {
  return speakers[speakerId];
}

export function getTalk(talkId) {
  return talks[talkId];
}

export function getTalkWithSpeaker(talkId) {
  const talk = talks[talkId];
  if (!talk) return null;

  return {
    ...talk,
    speaker: speakers[talk.speakerId],
  };
}

export function getSpeakersByGroup(group) {
  return Object.values(speakers).filter((speaker) => speaker.group === group);
}

export function getTalksByDay(day) {
  return Object.values(talks).filter((talk) => talk.day === day);
}

export function getTalksByTrack(track) {
  return Object.values(talks).filter((talk) => talk.track === track);
}
