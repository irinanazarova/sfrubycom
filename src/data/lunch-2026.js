// (src/lib/llm-content.js), and read by scripts/px-lunch.mjs, which draws the map
// and prints the walks.
//
// Sourced in November 2026. Recheck before the conference:
// - `yelp` and `reviews` are what Yelp's own listing showed.
// - `lunch` is one typical main in dollars, before tax and tip, from the menu
//   `menu` links to. Patxi's is the exception, since its own menu has no prices:
//   `lunchNote` says so.
// - `menu` links were each opened in a real browser. Lers Ros's /menu path is a
//   404; its site links menu.pdf. Nojo's old domain, nojosf.com, now redirects to
//   a spam site, so never link it. Several restaurant sites block automated
//   checks, so a link checker reports false failures on them.
// - `seats` is an estimate. Only RT Rotisserie (Time Out), Souvla (Tablehopper,
//   2014) and Sforno (SF Standard, March 2026: about six, plus some sidewalk
//   tables) have a published count. The rest are guesses from the room.
// - `walk` is minutes from the SFJAZZ door along the street grid at 75 m a minute.
//   scripts/px-lunch.mjs prints these from `lat`/`lon`.
// - Pacifico runs lunch in b-side, the bar inside SFJAZZ. Its own site is the
//   source for hours (closed Tuesday, Wednesday 11:30 am to 2:30 pm); Yelp says
//   2 pm and SFJAZZ's b-side page lists evenings only. `seats` is BizBash's 110
//   seated for the b-side room, which may not all be open at lunch.
//   Yelp's /biz/pacifico-san-francisco is a different place, at the Ferry Building.
// Not listed for lunch: Absinthe (OpenTable still shows a weekday lunch, but its
// own site opens at 4 pm on Tuesday and Wednesday), and Suppenküche and Zuni
// (dinner only on these days, per listings).

