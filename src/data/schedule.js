// Helper functions
export function getSlot(slotId) {
  return scheduleSlots[slotId];
}

export function getTalkIdForSlot(slotId) {
  return slotAssignments[slotId];
}

export function getSlotsByDay(day) {
  return Object.values(scheduleSlots).filter((slot) => slot.day === day);
}

export function getSlotsByTrack(track) {
  return Object.values(scheduleSlots).filter((slot) => slot.track === track);
}

export function getSlotsByType(type) {
  return Object.values(scheduleSlots).filter((slot) => slot.type === type);
}

// Get all slots with their assigned talks (requires talks data)
export function getSlotsWithTalks(talks) {
  return Object.entries(slotAssignments).map(([slotId, talkId]) => {
    const slot = scheduleSlots[slotId];
    const talk = talks[talkId];
    return {
      ...slot,
      talk: talk || null,
      talkId: talkId,
    };
  });
}

// Format time for display
export function formatTimeRange(slot) {
  return `${slot.startTime} - ${slot.endTime}`;
}

// Get track display name
export function getTrackDisplayName(track) {
  const trackNames = {
    main: "Main Track",
    blackbox: "Blackbox Theater",
    workshop: "Workshops",
  };
  return trackNames[track] || track;
}

// Swap talks between two slots
export function swapTalks(slotId1, slotId2) {
  const temp = slotAssignments[slotId1];
  slotAssignments[slotId1] = slotAssignments[slotId2];
  slotAssignments[slotId2] = temp;
  return slotAssignments;
}

// Assign a talk to a slot
export function assignTalkToSlot(slotId, talkId) {
  if (!scheduleSlots[slotId]) {
    throw new Error(`Slot ${slotId} does not exist`);
  }
  slotAssignments[slotId] = talkId;
  return slotAssignments;
}

// Remove a talk from a slot
export function removeTalkFromSlot(slotId) {
  delete slotAssignments[slotId];
  return slotAssignments;
}

// Get all unassigned talks (requires talks data)
export function getUnassignedTalks(talks) {
  const assignedTalkIds = new Set(Object.values(slotAssignments));
  return Object.keys(talks).filter((talkId) => !assignedTalkIds.has(talkId));
}

// Get conflicting slots (same time, different tracks)
export function getConflictingSlots(slotId) {
  const slot = scheduleSlots[slotId];
  if (!slot) return [];

  return Object.values(scheduleSlots).filter(
    (s) =>
      s.day === slot.day && s.startTime === slot.startTime && s.id !== slotId,
  );
}

// Get schedule for a specific day and track
export function getScheduleForDayAndTrack(day, track) {
  return Object.entries(scheduleSlots)
    .filter(([_, slot]) => slot.day === day && slot.track === track)
    .sort(([_, a], [__, b]) => {
      // Convert time strings to comparable format
      const timeToMinutes = (time) => {
        const [hours, minutes] = time.split(":").map(Number);
        return hours * 60 + minutes;
      };
      return timeToMinutes(a.startTime) - timeToMinutes(b.startTime);
    })
    .map(([slotId, slot]) => ({
      ...slot,
      talkId: slotAssignments[slotId] || null,
    }));
}

// Validate schedule consistency
export function validateSchedule(talks) {
  const errors = [];

  // Check for duplicate talk assignments
  const talkAssignments = {};
  Object.entries(slotAssignments).forEach(([slotId, talkId]) => {
    if (talkAssignments[talkId]) {
      errors.push(
        `Talk ${talkId} is assigned to multiple slots: ${talkAssignments[talkId]} and ${slotId}`,
      );
    }
    talkAssignments[talkId] = slotId;
  });

  // Check for non-existent slots
  Object.keys(slotAssignments).forEach((slotId) => {
    if (!scheduleSlots[slotId]) {
      errors.push(`Assignment references non-existent slot: ${slotId}`);
    }
  });

  // Check for non-existent talks
  if (talks) {
    Object.values(slotAssignments).forEach((talkId) => {
      if (!talks[talkId]) {
        errors.push(`Assignment references non-existent talk: ${talkId}`);
      }
    });
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}

// Get time blocks (for UI rendering)
export function getTimeBlocks(day) {
  const slots = getSlotsByDay(day);
  const timeBlocks = new Map();

  slots.forEach((slot) => {
    const timeKey = `${slot.startTime}-${slot.endTime}`;
    if (!timeBlocks.has(timeKey)) {
      timeBlocks.set(timeKey, {
        startTime: slot.startTime,
        endTime: slot.endTime,
        slots: [],
      });
    }
    timeBlocks.get(timeKey).slots.push(slot);
  });

  // Sort by start time
  return Array.from(timeBlocks.values()).sort((a, b) => {
    const timeToMinutes = (time) => {
      const [hours, minutes] = time.split(":").map(Number);
      return hours * 60 + minutes;
    };
    return timeToMinutes(a.startTime) - timeToMinutes(b.startTime);
  });
}

// Export schedule data as JSON
export function exportScheduleData() {
  return {
    slots: scheduleSlots,
    assignments: slotAssignments,
    metadata: {
      exportedAt: new Date().toISOString(),
      totalSlots: Object.keys(scheduleSlots).length,
      assignedSlots: Object.keys(slotAssignments).length,
    },
  };
}

// Import schedule data from JSON
export function importScheduleData(data) {
  if (data.slots) {
    Object.assign(scheduleSlots, data.slots);
  }
  if (data.assignments) {
    Object.assign(slotAssignments, data.assignments);
  }
  return {
    slots: scheduleSlots,
    assignments: slotAssignments,
  };
}
